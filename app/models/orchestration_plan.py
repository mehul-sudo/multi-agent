"""
OrchestrationPlan, PlanTask, and TaskDependency models.

Represents structured DAG execution plans generated by the Planner Agent.
"""

import uuid
from datetime import datetime, timezone

from app.extensions import db

PLAN_TASK_STATUS_PENDING = "PENDING"
PLAN_TASK_STATUS_READY = "READY"
PLAN_TASK_STATUS_RUNNING = "RUNNING"
PLAN_TASK_STATUS_AWAITING_APPROVAL = "AWAITING_APPROVAL"
PLAN_TASK_STATUS_AWAITING_DELEGATION = "AWAITING_DELEGATION"
PLAN_TASK_STATUS_REVIEWING = "REVIEWING"
PLAN_TASK_STATUS_COMPLETED = "COMPLETED"
PLAN_TASK_STATUS_FAILED = "FAILED"
PLAN_TASK_STATUS_CANCELLED = "CANCELLED"
PLAN_TASK_STATUS_SKIPPED = "SKIPPED"

SUPPORTED_PLAN_TASK_STATUSES = (
    PLAN_TASK_STATUS_PENDING,
    PLAN_TASK_STATUS_READY,
    PLAN_TASK_STATUS_RUNNING,
    PLAN_TASK_STATUS_AWAITING_APPROVAL,
    PLAN_TASK_STATUS_AWAITING_DELEGATION,
    PLAN_TASK_STATUS_REVIEWING,
    PLAN_TASK_STATUS_COMPLETED,
    PLAN_TASK_STATUS_FAILED,
    PLAN_TASK_STATUS_CANCELLED,
    PLAN_TASK_STATUS_SKIPPED,
)


def _utcnow() -> datetime:
    return datetime.now(timezone.utc).replace(tzinfo=None)


class OrchestrationPlan(db.Model):
    """An execution plan generated for an OrchestrationSession."""

    __tablename__ = "orchestration_plans"

    id = db.Column(db.Integer, primary_key=True, autoincrement=True)

    public_id = db.Column(
        db.String(36),
        unique=True,
        index=True,
        nullable=False,
        default=lambda: str(uuid.uuid4()),
    )

    orchestration_id = db.Column(
        db.Integer, db.ForeignKey("orchestration_sessions.id", use_alter=True, name="fk_plan_orchestration"), index=True, nullable=False
    )
    version = db.Column(db.Integer, nullable=False, default=1)

    objective = db.Column(db.Text, nullable=False)
    assumptions = db.Column(db.JSON, nullable=False, default=list)

    is_active = db.Column(db.Boolean, nullable=False, default=True)
    validation_status = db.Column(db.String(20), nullable=False, default="VALIDATED")

    estimated_cost = db.Column(db.Float, nullable=False, default=0.0)
    estimated_duration = db.Column(db.Integer, nullable=False, default=0)

    failure_strategy = db.Column(db.String(50), nullable=False, default="REPLAN")
    rollback_info = db.Column(db.JSON, nullable=False, default=dict)

    created_at = db.Column(db.DateTime, nullable=False, default=_utcnow)
    updated_at = db.Column(db.DateTime, nullable=False, default=_utcnow, onupdate=_utcnow)

    # Relationships
    tasks = db.relationship("PlanTask", backref="plan", lazy="dynamic", cascade="all, delete-orphan")

    def __repr__(self) -> str:
        return f"<OrchestrationPlan public_id={self.public_id} v={self.version}>"


class PlanTask(db.Model):
    """An individual task within an OrchestrationPlan."""

    __tablename__ = "plan_tasks"

    id = db.Column(db.Integer, primary_key=True, autoincrement=True)

    public_id = db.Column(
        db.String(36),
        unique=True,
        index=True,
        nullable=False,
        default=lambda: str(uuid.uuid4()),
    )

    plan_id = db.Column(db.Integer, db.ForeignKey("orchestration_plans.id"), index=True, nullable=False)
    task_key = db.Column(db.String(100), nullable=False)  # Task identifier inside the DAG (e.g. task_1, research_step)

    name = db.Column(db.String(150), nullable=False)
    description = db.Column(db.Text, nullable=True)
    task_type = db.Column(db.String(50), nullable=False, default="agent_task")  # agent_task, human_approval, review, delegation

    assigned_agent_id = db.Column(db.Integer, db.ForeignKey("agents.id"), nullable=True)
    assigned_agent_version = db.Column(db.Integer, nullable=True)

    required_capabilities = db.Column(db.JSON, nullable=False, default=list)
    input_references = db.Column(db.JSON, nullable=False, default=dict)
    output_schema = db.Column(db.JSON, nullable=False, default=dict)

    conditional_rules = db.Column(db.JSON, nullable=False, default=dict)
    retry_policy = db.Column(db.JSON, nullable=False, default=dict)
    timeout_seconds = db.Column(db.Integer, nullable=False, default=300)
    priority = db.Column(db.Integer, nullable=False, default=1)
    idempotency_key = db.Column(db.String(100), nullable=True)

    approval_requirement = db.Column(db.JSON, nullable=False, default=dict)
    status = db.Column(db.String(30), nullable=False, default=PLAN_TASK_STATUS_PENDING)
    attempt_count = db.Column(db.Integer, nullable=False, default=0)

    parent_task_id = db.Column(db.Integer, db.ForeignKey("plan_tasks.id"), nullable=True)
    delegation_depth = db.Column(db.Integer, nullable=False, default=0)

    output_data = db.Column(db.JSON, nullable=False, default=dict)
    error_message = db.Column(db.Text, nullable=True)

    started_at = db.Column(db.DateTime, nullable=True)
    completed_at = db.Column(db.DateTime, nullable=True)
    created_at = db.Column(db.DateTime, nullable=False, default=_utcnow)
    updated_at = db.Column(db.DateTime, nullable=False, default=_utcnow, onupdate=_utcnow)

    # Relationships
    assigned_agent = db.relationship("Agent")
    parent_task = db.relationship("PlanTask", remote_side=[id], backref=db.backref("subtasks", lazy="dynamic"))

    def __repr__(self) -> str:
        return f"<PlanTask key={self.task_key!r} status={self.status}>"


class TaskDependency(db.Model):
    """Dependency link between tasks in a plan DAG (parent -> child)."""

    __tablename__ = "task_dependencies"

    id = db.Column(db.Integer, primary_key=True, autoincrement=True)

    plan_id = db.Column(db.Integer, db.ForeignKey("orchestration_plans.id"), index=True, nullable=False)
    parent_task_id = db.Column(db.Integer, db.ForeignKey("plan_tasks.id"), index=True, nullable=False)
    child_task_id = db.Column(db.Integer, db.ForeignKey("plan_tasks.id"), index=True, nullable=False)

    dependency_type = db.Column(db.String(20), nullable=False, default="required")  # required, optional, conditional

    created_at = db.Column(db.DateTime, nullable=False, default=_utcnow)

    parent_task = db.relationship("PlanTask", foreign_keys=[parent_task_id], backref=db.backref("downstream_dependencies", lazy="dynamic"))
    child_task = db.relationship("PlanTask", foreign_keys=[child_task_id], backref=db.backref("upstream_dependencies", lazy="dynamic"))

    def __repr__(self) -> str:
        return f"<TaskDependency parent={self.parent_task_id} -> child={self.child_task_id}>"
